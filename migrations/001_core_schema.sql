-- ─────────────────────────────────────────────────────────────────────────────
-- Derived objects
--
-- daily_product_sales is a materialised view rather than a seeded table so it
-- can never disagree with sale_lines. `make seed` refreshes it after loading.
-- ─────────────────────────────────────────────────────────────────────────────

CREATE MATERIALIZED VIEW daily_product_sales AS
SELECT
    sl.store_id,
    sl.product_id,
    sl.business_date,
    COALESCE(sum(sl.quantity)  FILTER (WHERE sl.quantity > 0), 0)  AS units_sold,
    COALESCE(-sum(sl.quantity) FILTER (WHERE sl.quantity < 0), 0)  AS return_units,
    sum(sl.quantity)                                               AS net_units,
    sum(sl.line_total)                                             AS net_revenue,
    sum(sl.quantity * sl.unit_cost)                                AS cogs
FROM sale_lines sl
GROUP BY sl.store_id, sl.product_id, sl.business_date;

COMMENT ON MATERIALIZED VIEW daily_product_sales IS
    'Per store, per product, per trading day sales rollup, derived from '
    'sale_lines. Refreshed by `make seed`. Gross, returns and net are named '
    'separately so no query has to remember that sale_lines.quantity is '
    'signed. Days with no sales have no row.';

COMMENT ON COLUMN daily_product_sales.units_sold IS
    'Units sold outward on this day. Positive quantities only — returns are '
    'excluded and counted separately. This is GROSS units.';
COMMENT ON COLUMN daily_product_sales.return_units IS
    'Units handed back on this day, as a POSITIVE number.';
COMMENT ON COLUMN daily_product_sales.net_units IS
    'units_sold minus return_units. This is the honest "how many did we move" '
    'figure and the right default for a sales-volume question.';
COMMENT ON COLUMN daily_product_sales.net_revenue IS
    'Takings for the day, NET of returns and NET of GST. Refund lines carry a '
    'negative line_total and are already subtracted. Add sales.tax_total if a '
    'question is about cash collected rather than revenue.';
COMMENT ON COLUMN daily_product_sales.cogs IS
    'Cost of goods sold, net of returns, using the cost frozen on each line at '
    'the time of sale. Margin for a period is net_revenue - cogs.';

CREATE UNIQUE INDEX daily_product_sales_pk_idx
    ON daily_product_sales (store_id, product_id, business_date);
CREATE INDEX daily_product_sales_date_idx ON daily_product_sales (business_date);

-- Trailing-30-day sales velocity.
--
-- The window is anchored on the latest trading day present in the data, NOT on
-- current_date. The seed has a fixed end date so it can be byte-identical on
-- re-run; a current_date-anchored view would return nothing the moment
-- wall-clock passed that date. Self-anchoring means this works on any day.
CREATE VIEW v_product_velocity_30d AS
WITH anchor AS (
    SELECT max(business_date) AS as_of_date FROM daily_product_sales
),
bounds AS (
    SELECT as_of_date, as_of_date - 29 AS from_date FROM anchor
),
sold AS (
    SELECT d.store_id, d.product_id,
           sum(d.net_units)     AS net_units_30d,
           sum(d.units_sold)    AS units_sold_30d,
           sum(d.net_revenue) AS revenue_30d
    FROM daily_product_sales d, bounds b
    WHERE d.business_date BETWEEN b.from_date AND b.as_of_date
    GROUP BY d.store_id, d.product_id
),
outages AS (
    SELECT s.store_id, s.product_id, count(*) AS stockout_days_30d
    FROM stockout_days s, bounds b
    WHERE s.business_date BETWEEN b.from_date AND b.as_of_date
    GROUP BY s.store_id, s.product_id
)
SELECT
    i.store_id,
    i.product_id,
    b.as_of_date,
    COALESCE(sold.units_sold_30d, 0)     AS units_sold_30d,
    COALESCE(sold.net_units_30d, 0)      AS net_units_30d,
    COALESCE(sold.revenue_30d, 0)::numeric(12,2) AS revenue_30d,
    COALESCE(o.stockout_days_30d, 0)     AS stockout_days_30d,
    30 - COALESCE(o.stockout_days_30d, 0) AS available_days_30d,
    round(COALESCE(sold.net_units_30d, 0)::numeric
          / GREATEST(30 - COALESCE(o.stockout_days_30d, 0), 1), 3) AS units_per_day
FROM inventory i
CROSS JOIN bounds b
LEFT JOIN sold    ON sold.store_id = i.store_id AND sold.product_id = i.product_id
LEFT JOIN outages o ON o.store_id  = i.store_id AND o.product_id   = i.product_id;

COMMENT ON VIEW v_product_velocity_30d IS
    'How fast each product sells at each store, over the 30 trading days '
    'ending on the most recent day present in the data. units_per_day divides '
    'by the days the product was actually AVAILABLE, not by 30, so a product '
    'that stocked out is not penalised for the days it could not be sold. One '
    'row per row of inventory, including products that sold nothing.';

CREATE VIEW v_supplier_terms_current AS
SELECT supplier_terms_id, supplier_id, payment_terms_days, lead_time_days,
       min_order_value, volume_discount_pct, returns_window_days,
       effective_from, source
FROM supplier_terms
WHERE effective_to IS NULL;

COMMENT ON VIEW v_supplier_terms_current IS
    'The supplier terms in force now — the rows with no end date. For terms as '
    'they stood on some past date, query supplier_terms with '
    'valid_period @> DATE ''YYYY-MM-DD'' instead. A supplier missing from this '
    'view has no terms currently in force, which is not the same as having no '
    'terms on record.';

CREATE VIEW v_supplier_price_current AS
SELECT supplier_price_id, supplier_id, product_id, unit_cost, currency,
       effective_from, source
FROM supplier_prices
WHERE effective_to IS NULL;

COMMENT ON VIEW v_supplier_price_current IS
    'The price each supplier currently charges for each product. For a price '
    'on a past date, query supplier_prices with valid_period @> DATE.';

CREATE VIEW v_stock_status AS
SELECT
    i.store_id,
    i.product_id,
    p.sku,
    p.name                AS product_name,
    c.name                AS category_name,
    c.department,
    i.on_hand,
    i.reorder_point,
    i.reorder_qty,
    (i.on_hand <= i.reorder_point) AS below_reorder_point,
    v.units_per_day,
    v.net_units_30d,
    v.stockout_days_30d,
    CASE WHEN v.units_per_day > 0
         THEN round(i.on_hand::numeric / v.units_per_day, 1)
    END                   AS days_of_cover,
    sp.supplier_id        AS preferred_supplier_id,
    s.name                AS preferred_supplier_name,
    t.lead_time_days,
    t.payment_terms_days,
    cp.unit_cost          AS current_unit_cost,
    sp.case_pack,
    sp.min_order_qty,
    COALESCE(oo.on_order_qty, 0) AS on_order_qty
FROM inventory i
JOIN products   p USING (product_id)
JOIN categories c USING (category_id)
LEFT JOIN v_product_velocity_30d v
       ON v.store_id = i.store_id AND v.product_id = i.product_id
LEFT JOIN supplier_products sp
       ON sp.product_id = i.product_id AND sp.is_preferred
LEFT JOIN suppliers s ON s.supplier_id = sp.supplier_id
LEFT JOIN v_supplier_terms_current t ON t.supplier_id = sp.supplier_id
LEFT JOIN v_supplier_price_current cp
       ON cp.supplier_id = sp.supplier_id AND cp.product_id = i.product_id
LEFT JOIN (
    SELECT po.store_id, pol.product_id,
           sum(pol.quantity_ordered - pol.quantity_received) AS on_order_qty
    FROM purchase_order_lines pol
    JOIN purchase_orders po USING (po_id)
    WHERE po.status IN ('draft', 'submitted')
    GROUP BY po.store_id, pol.product_id
) oo ON oo.store_id = i.store_id AND oo.product_id = i.product_id;

COMMENT ON VIEW v_stock_status IS
    'One row per store per product: what is on the shelf, how fast it moves, '
    'how long the shelf will last, who supplies it and on what terms, and how '
    'much is already on order. days_of_cover is on_hand divided by daily '
    'velocity — low days_of_cover means running out soon. NULL days_of_cover '
    'means the product has not sold in the last 30 days, which is different '
    'from running out fast.';


